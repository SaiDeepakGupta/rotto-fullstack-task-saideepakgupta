// Writes .env.local with the local Supabase URL and keys printed by `supabase status`.
// The model key and STRIPE_WEBHOOK_SECRET are not written: they come from your environment.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

// On Windows npx is npx.cmd, which only resolves through a shell.
const out = execFileSync("npx", ["supabase", "status", "-o", "env"], {
  encoding: "utf8",
  shell: process.platform === "win32",
});
const vars = Object.fromEntries(
  [...out.matchAll(/^([A-Z_]+)="?([^"\n]*)"?$/gm)].map(([, key, value]) => [key, value]),
);

for (const key of ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"]) {
  if (!vars[key]) throw new Error(`supabase status did not report ${key}. Is Supabase running?`);
}

writeFileSync(
  ".env.local",
  [
    "# Generated by `make setup` from `supabase status`. Do not commit.",
    `NEXT_PUBLIC_SUPABASE_URL=${vars.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${vars.ANON_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${vars.SERVICE_ROLE_KEY}`,
    "",
  ].join("\n"),
);
console.log("Wrote .env.local");
